        await SecureStorageService.saveCredentials(
          normalizedEmail,
          userId: user['id']?.toString(),
        );
      } else {
        await SecureStorageService.clearCredentials();
      }

      notifyListeners();
      _startAutoBackupTimer();
      return true;
    } catch (e) {
      log('Login error: $e');
      return false;
